/**
 * Lint-Warnings Audit Script
 *
 * Reads lint-audit.json and produces a separate report containing only
 * warning-level findings (severity === 1 or 'warning'), with recomputed
 * per-file scores and P0/P1/P2 priority for the warnings-only view.
 *
 * Run audit:lint first to generate lint-audit.json.
 *
 * Output: .audit-reports/lint-warnings-audit.json, .audit-reports/lint-warnings-audit.md
 */

import fs from 'node:fs'
import path from 'node:path'
import { getAuditReportHeaderLines, resolveAuditPaths, writeAuditReports } from './shared-audit-utils.mjs'

function assignPriority(score, config) {
  const p0Min = Number(config?.priorities?.p0MinSeverityScore ?? 15)
  const p1Min = Number(config?.priorities?.p1MinSeverityScore ?? 6)
  if (score >= p0Min) return 'P0'
  if (score >= p1Min) return 'P1'
  return 'P2'
}

function isWarning(finding) {
  return finding.severity === 1 || finding.severity === 'warning'
}

function renderMarkdownReport(result) {
  const lines = []
  lines.push('# Lint-Warnings Audit (Generated)')
  lines.push('')
  lines.push(...getAuditReportHeaderLines())
  lines.push('')
  lines.push('Generated by `client/.scripts/lint-warnings-audit.mjs`. Warnings only (severity 1).')
  lines.push('')
  lines.push('## Summary')
  lines.push('')
  lines.push(`- Files with warnings: **${result.files.length}**`)
  lines.push(`- Total warning findings: **${result.findings.length}**`)
  lines.push('')

  const byRule = {}
  for (const f of result.findings) {
    byRule[f.ruleId] = (byRule[f.ruleId] || 0) + 1
  }
  lines.push('| Rule | Count |')
  lines.push('| --- | ---: |')
  for (const [ruleId, count] of Object.entries(byRule).sort((a, b) => b[1] - a[1])) {
    lines.push(`| ${ruleId} | ${count} |`)
  }
  lines.push('')

  if (result.files.length > 0) {
    lines.push('## Files by Severity')
    lines.push('')
    lines.push('| File | Priority | Score |')
    lines.push('| --- | --- | ---: |')
    for (const f of result.files.slice(0, 40)) {
      lines.push(`| \`${f.file}\` | ${f.priority} | ${f.score} |`)
    }
    if (result.files.length > 40) {
      lines.push(`| *...and ${result.files.length - 40} more* | | |`)
    }
    lines.push('')
  }

  return lines.join('\n')
}

function main() {
  const paths = resolveAuditPaths('lint-warnings')
  const lintAuditJson = path.join(paths.outDir, 'lint-audit.json')
  const lintConfigPath = path.join(paths.outDir, 'lint-audit-config.json')

  if (!fs.existsSync(lintAuditJson)) {
    console.error('lint-audit.json not found. Run: npm run audit:lint')
    process.exitCode = 1
    return
  }

  let config = {}
  try {
    if (fs.existsSync(lintConfigPath)) {
      config = JSON.parse(fs.readFileSync(lintConfigPath, 'utf8'))
    }
  } catch {
    /* defaults */
  }

  const lintAudit = JSON.parse(fs.readFileSync(lintAuditJson, 'utf8'))
  const warningsOnly = (lintAudit.findings || []).filter(isWarning)

  const fileScores = new Map()
  for (const f of warningsOnly) {
    const repoPath = f.repoPath || f.file
    const weight = (config.ruleWeights && config.ruleWeights[f.ruleId]) ?? 1
    fileScores.set(repoPath, (fileScores.get(repoPath) || 0) + weight)
  }

  const files = Array.from(fileScores.entries())
    .map(([file, score]) => ({
      file,
      repoPath: file,
      score,
      priority: assignPriority(score, config),
    }))
    .sort((a, b) => b.score - a.score)

  const result = {
    generatedAt: new Date().toISOString(),
    totalScanned: files.length,
    findings: warningsOnly,
    files,
  }

  const { outJson, outMd } = writeAuditReports('lint-warnings', result, renderMarkdownReport(result))

  console.log(`Wrote:\n- ${outJson}\n- ${outMd}`)
  console.log(`Warning findings: ${warningsOnly.length} (files: ${files.length})`)
  process.exitCode = 0
}

main()
