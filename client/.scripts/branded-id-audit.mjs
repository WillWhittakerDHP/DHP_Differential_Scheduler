import fs from 'node:fs'
import path from 'node:path'
import { getAuditReportHeaderLines, listAuditFiles } from './shared-audit-utils.mjs'

/**
 * Branded ID Audit Script
 *
 * Goal: Produce a deterministic inventory of sites that need refactoring when
 * GlobalEntityId is branded (string & { __brand: 'GlobalEntityId' }).
 *
 * Rules:
 * 1. as-globalentityid — "as GlobalEntityId" assertions → replace with toGlobalEntityId(expr)
 * 2. string-id-param — function params like parentId: string → change to GlobalEntityId
 * 3. string-wrap-id — String(x.id) or String(entityId) → remove wrapper after branding
 *
 * Scope: client/src only (.ts, .vue). Excluded: __tests__, *.test.*, *.spec.*, @core, @layouts
 *
 * Output: client/.audit-reports/branded-id-audit.json, branded-id-audit.md
 */

const CWD = path.resolve(process.cwd())
const IS_CLIENT_DIR = fs.existsSync(path.join(CWD, 'src'))
const PROJECT_ROOT = IS_CLIENT_DIR ? path.resolve(CWD, '..') : CWD
const CLIENT_ROOT = IS_CLIENT_DIR ? CWD : path.join(PROJECT_ROOT, 'client')
const CLIENT_SRC = path.join(CLIENT_ROOT, 'src')

const OUT_DIR = fs.existsSync(CLIENT_SRC)
  ? path.join(CWD, '.audit-reports')
  : path.join(CWD, 'client', '.audit-reports')
const OUT_JSON = path.join(OUT_DIR, 'branded-id-audit.json')
const OUT_MD = path.join(OUT_DIR, 'branded-id-audit.md')

function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true })
}

function toRepoPath(absPath) {
  return path.relative(PROJECT_ROOT, absPath).replaceAll(path.sep, '/')
}

function splitLines(contents) {
  return contents.replaceAll('\r\n', '\n').split('\n')
}

/** Line-based scan for three rules. Returns { ruleId, lineNumber, snippet }[] */
function scanFile(lines, _repoPath) {
  const findings = []
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i]
    const lineNum = i + 1
    const trimmed = line.trim()

    // Rule 1: as GlobalEntityId (and as GlobalEntityId | null)
    if (/as\s+GlobalEntityId/.test(line)) {
      findings.push({ ruleId: 'as-globalentityid', lineNumber: lineNum, snippet: trimmed })
    }

    // Rule 2: param name ending in Id (or Id + word) with : string (not branded string & ...)
    // Match: parentId: string, childId: string, entityId: string, blockInstanceId: string, etc.
    if (/\b(\w*[iI]d\w*)\s*:\s*string\b/.test(line) && !/\bstring\s*&/.test(line)) {
      findings.push({ ruleId: 'string-id-param', lineNumber: lineNum, snippet: trimmed })
    }

    // Rule 3: String( something.id ) or String( somethingId ) — defensive wrap to remove after branding
    if (/String\s*\(\s*[^)]+\)/.test(line)) {
      const argMatch = line.match(/String\s*\(\s*([^)]+)\)/)
      if (argMatch) {
        const arg = argMatch[1].trim()
        const looksLikeId =
          /\.(id|Id)\s*$/.test(arg) ||
          /\w+Id\s*$/.test(arg) ||
          /^\s*id\s*$/.test(arg)
        if (looksLikeId) {
          findings.push({ ruleId: 'string-wrap-id', lineNumber: lineNum, snippet: trimmed })
        }
      }
    }
  }
  return findings
}

function renderMarkdownReport(data) {
  const { generatedAt: _generatedAt, scope, fileCount, files, summary } = data
  const lines = []
  lines.push(...getAuditReportHeaderLines())
  lines.push('# Branded ID Audit (Generated)')
  lines.push('')
  lines.push('Generated by `client/.scripts/branded-id-audit.mjs`.')
  lines.push('')
  lines.push('Scope:')
  lines.push(`- Included: ${scope.included.join(', ')}`)
  lines.push(`- Excluded: ${scope.excluded.join(', ')}`)
  lines.push('')
  lines.push('## Summary')
  lines.push('')
  lines.push(`- Files scanned: **${fileCount}**`)
  lines.push(`- Total findings: **${summary.total}**`)
  lines.push(`- as-globalentityid: **${summary.asGlobalentityid}**`)
  lines.push(`- string-id-param: **${summary.stringIdParam}**`)
  lines.push(`- string-wrap-id: **${summary.stringWrapId}**`)
  lines.push('')
  lines.push('## Findings by File')
  lines.push('')

  const filesWithFindings = files.filter((f) => f.findings.length > 0).sort((a, b) => a.repoPath.localeCompare(b.repoPath))
  for (const f of filesWithFindings) {
    lines.push(`### \`${f.repoPath}\` (${f.findings.length} findings)`)
    lines.push('')
    for (const m of f.findings) {
      lines.push(`- [${m.ruleId}]@${m.lineNumber}: \`${m.snippet.replaceAll('`', '\\`')}\``)
    }
    lines.push('')
  }

  if (filesWithFindings.length === 0) {
    lines.push('No findings.')
    lines.push('')
  }

  return lines.join('\n')
}

function main() {
  ensureDir(OUT_DIR)
  const absFiles = listAuditFiles('branded-id', [CLIENT_SRC])
  const files = []
  const summary = { total: 0, asGlobalentityid: 0, stringIdParam: 0, stringWrapId: 0 }

  for (const abs of absFiles) {
    const repoPath = toRepoPath(abs)
    const contents = fs.readFileSync(abs, 'utf8')
    const lines = splitLines(contents)
    const findings = scanFile(lines, repoPath)
    if (findings.length > 0) {
      for (const m of findings) {
        summary.total += 1
        if (m.ruleId === 'as-globalentityid') summary.asGlobalentityid += 1
        else if (m.ruleId === 'string-id-param') summary.stringIdParam += 1
        else if (m.ruleId === 'string-wrap-id') summary.stringWrapId += 1
      }
      files.push({ repoPath, findings })
    }
  }

  const out = {
    generatedAt: new Date().toISOString(),
    scope: {
      included: ['client/src/**/*.ts', 'client/src/**/*.vue'],
      excluded: ['**/__tests__/**', '**/*.test.*', '**/*.spec.*', 'client/src/@core/**', 'client/src/@layouts/**'],
    },
    fileCount: absFiles.length,
    summary,
    files,
  }

  fs.writeFileSync(OUT_JSON, JSON.stringify(out, null, 2))
  fs.writeFileSync(OUT_MD, renderMarkdownReport(out))

  console.log(
    `Wrote:\n- ${toRepoPath(OUT_JSON)}\n- ${toRepoPath(OUT_MD)}\nFiles scanned: ${absFiles.length}, Files with findings: ${files.length}, Total findings: ${summary.total}`
  )
  process.exitCode = 0
}

main()
